/** Одна строка фактов внутри кейса. Поле, которого нет в данных, не рендерится. */
export interface CollaborationFact {
  label: string
  value: string
}

export interface Collaboration {
  /** slug проекта в CMS — источник обложки, названия и ссылки */
  slug: string
  /** Как называем сферу клиента. Берётся из описания проекта */
  field: string
  facts: CollaborationFact[]
  /** Варианты композиции: четыре одинаковые карточки подряд — не кейсы, а каталог */
  layout: 'image-left' | 'image-right-offset' | 'band' | 'portrait'
}

