/**
 * Этап процесса, где речь о форматах (16:9, 9:16, 1:1), получает наглядную
 * линейку форматов. Привязка не по номеру шага, а по плашке: этапы редактируются
 * в админке и заменяют код целиком, и линейка под этапом, где про форматы уже
 * не говорится, была бы неверной. Убрали плашку: линейка исчезает сама.
 */
const FORMAT_CHIP = /(^|[^\d])16\s*:\s*9([^\d]|$)/

export function hasFormatChip(items: readonly string[]): boolean {
  return items.some(item => FORMAT_CHIP.test(item))
}
