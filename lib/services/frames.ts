/**
 * Раскадровка раздела направлений.
 *
 * У каждой работы в портфолио лежит галерея кадров, но страница всё это время
 * брала из неё только первый. Он не выбирался — он просто оказывался первым в
 * массиве, и именно поэтому реклама открывалась мягким расфокусированным
 * планом, а beauty держалась на тёмном видео, в котором фактуры не видно.
 *
 * Здесь лежит выбор: какая работа открывает территорию и какой её кадр стоит
 * в сцене. Это раскадровка, а не конфигурация бизнеса — состав направлений,
 * маршруты и доказательства живут в directions.ts и здесь не меняются. Отсюда
 * же берутся кадры монтажа первого экрана: сцена и монтаж обязаны показывать
 * одно и то же.
 *
 * Критерий отбора был один: кадр должен держать полный экран до того, как на
 * него ляжет типографика. Если набор нужен, чтобы сделать кадр интересным,
 * кадр выбран неправильно.
 */
import type { ServiceDirectionId } from './directions'

export interface DirectionFrames {
  /**
   * Работа, которая открывает территорию. Она же уходит первым планом в
   * монтаж первого экрана. Без неё порядок берётся из proofSlugs.
   */
  lead?: string
  /**
   * Номер кадра в галерее работы. Одна и та же съёмка может отдавать разным
   * территориям разные планы: WELLERY стоит в регулярном продакшне
   * гостиничным номером, в корпоративном — руками с продуктом, а в AI —
   * выкладкой на светлом.
   */
  still: Partial<Record<string, number>>
}

