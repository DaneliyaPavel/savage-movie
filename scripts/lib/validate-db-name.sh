#!/bin/bash
# Проверка имени базы данных перед записью в .env.
# Подключается через `source` из scripts/deploy.sh и scripts/prod-up.sh, сама ничего не запускает.
#
# Зачем. sync_db_name_from_running_db берёт имя базы из работающего Postgres
# (pg_database), пишет его в .env через sed, а deploy.sh затем делает
# `set -a; . "$ENV_FILE"`, то есть исполняет .env как shell. Postgres разрешает
# в имени базы почти любые символы, поэтому тот, у кого есть права суперпользователя БД,
# мог назвать базу `a$(команда)`, `a;команда` или `x\nP=$(команда)` (GNU sed превращает
# \n в перевод строки) и получить выполнение команд на сервере при следующем деплое.
#
# Допускаем только обычный идентификатор Postgres без кавычек: буква или _, дальше
# буквы, цифры, _ (такое же правило уже стоит в scripts/restore.sh). Имя со
# дефисом или точкой в .env автоматически не попадёт: DB_NAME тогда задают вручную.

# is_valid_db_name <имя>: 0, если имя безопасно писать в .env, иначе 1.
is_valid_db_name() {
  local name="${1-}"
  # C-локаль: диапазоны a-z и длина считаются по байтам, без сюрпризов от кириллицы
  local LC_ALL=C

  [ -n "$name" ] || return 1
  # лимит идентификатора Postgres — 63 байта
  [ "${#name}" -le 63 ] || return 1

  # case, а не regex: перевод строки в конце имени не должен проходить мимо `$`
  case "$name" in
    [!a-zA-Z_]*|*[!a-zA-Z0-9_]*) return 1 ;;
  esac
  return 0
}

# warn_invalid_db_name <имя>: сообщение, что имя отклонено. Само имя печатаем через %q,
# чтобы управляющие символы и escape-последовательности не попали в лог как есть.
warn_invalid_db_name() {
  printf '⚠️  Имя базы %q не похоже на обычный идентификатор (буквы, цифры, _), в .env не записываю.\n' "${1-}"
  echo "   Проверь пользователей и базы в Postgres: имя могли подменить. DB_NAME задай в .env вручную."
}

# is_safe_env_db_value <значение после DB_NAME=>: 0, если строку .env можно исполнить
# через `source`, ничего не запустив. Правило мягче is_valid_db_name: значение, которое
# владелец уже держит в .env (с дефисом, точкой, в кавычках, с комментарием в конце),
# не должно останавливать деплой; нужно только, чтобы в нём не было подстановок,
# разделителей команд и пробелов внутри значения.
is_safe_env_db_value() {
  local value="${1-}"
  local LC_ALL=C
  local quote="'"
  local name='[A-Za-z0-9_.-]*'
  local pattern="^(\"$name\"|$quote$name$quote|$name)([[:space:]]+#.*|[[:space:]]*)\$"

  [[ "$value" =~ $pattern ]]
}

# find_unsafe_db_name_in_env <файл .env>: если какая-то строка DB_NAME=... опасна для
# `source`, печатает её значение (через %q) и возвращает 0, иначе возвращает 1.
#
# Зачем. is_valid_db_name защищает запись в .env, но не то, что уже в нём лежит: .env мог
# быть отравлен прежней версией скрипта (она писала любое имя базы). Тогда каждый деплой
# заново исполнял бы подстановку, пока база с таким именем существует. Строки вида
# `DB_NAME=x` + отдельная `P=$(...)` (из имени с \n) эта проверка не видит: после первого
# деплоя на VPS надо один раз выполнить grep -nE '\$\(|`' .env и убедиться, что пусто.
find_unsafe_db_name_in_env() {
  local file="${1-}"
  local line value

  [ -f "$file" ] || return 1
  while IFS= read -r line || [ -n "$line" ]; do
    # shell примет и отступ, и export перед присваиванием
    line="${line#"${line%%[![:space:]]*}"}"
    line="${line#export }"
    case "$line" in
      DB_NAME=*) ;;
      *) continue ;;
    esac
    value="${line#DB_NAME=}"
    if ! is_safe_env_db_value "$value"; then
      printf '%q' "$value"
      return 0
    fi
  done < "$file"
  return 1
}
