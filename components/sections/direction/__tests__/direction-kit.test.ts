import { describe, expect, it } from 'vitest'

import { typo } from '../direction-kit'

const NBSP = '\u00A0'

describe('typo', () => {
  it('связывает цепочку коротких слов целиком', () => {
    expect(typo('о чём и как')).toBe(`о${NBSP}чём${NBSP}и${NBSP}как`)
    expect(typo('и в ней')).toBe(`и${NBSP}в${NBSP}ней`)
  })

  it('тянет за предлогом короткое слово и следующее: «в конце концов»', () => {
    expect(typo('в конце концов')).toBe(`в${NBSP}конце${NBSP}концов`)
  })

  it('не тянет цепочку дальше фразы из трёх слов', () => {
    expect(typo('на том конце провода')).toBe(`на${NBSP}том${NBSP}конце провода`)
  })

  it('не оставляет короткое слово последним в строке, длинные слова не трогает', () => {
    expect(typo('Что снимем')).toBe(`Что${NBSP}снимем`)
    expect(typo('Снимаем клипы')).toBe('Снимаем клипы')
  })

  it('держит тире у слова слева и число рядом с единицей', () => {
    expect(typo('слово — слово')).toBe(`слово${NBSP}— слово`)
    expect(typo('за 5 минут и 30 % работы')).toBe(
      `за${NBSP}5${NBSP}минут и${NBSP}30${NBSP}% работы`
    )
  })

  it('открывающая кавычка и скобка не мешают', () => {
    expect(typo('«в тени» (а потом)')).toBe(`«в${NBSP}тени» (а${NBSP}потом)`)
  })

  it('ограничивает неразрывную цепочку, чтобы она не вылезла за край', () => {
    const chain = Array.from({ length: 30 }, () => 'ab').join(' ')
    expect(typo(chain)).toContain(' ')
  })

  it('не приклеивает пробел к пустому хвосту', () => {
    expect(typo('Что нельзя ')).toBe(`Что${NBSP}нельзя `)
  })

  it('повторный вызов ничего не меняет', () => {
    for (const sample of [
      'о чём и как',
      'в конце концов',
      'Что снимем на весь квартал',
      'за 5 минут — и в кадре',
    ]) {
      expect(typo(typo(sample))).toBe(typo(sample))
    }
  })
})
